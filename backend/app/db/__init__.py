# db/ 包 —— 数据库访问层
#
# 这个包集中管理所有数据库相关代码。
# 【为什么要把数据库代码独立出来？】
# 如果把 SQL 散落在各个业务文件中，以后要改表结构或换数据库，
# 得满项目找 SQL 语句。集中管理后，改动只需在 db/ 下进行。
#
# 各文件职责：
# - session.py：创建数据库连接，提供 AsyncSession 给业务代码用
# - base.py：ORM 基类，所有模型都继承它
# - models.py：所有数据表对应的 Python 类（ORM 模型）
# - repositories/：对每个模型做增删改查，业务代码不直接写 SQL
# - seed.py：首次启动时创建默认管理员和角色
#
# 【学习顺序建议】
# 1. 先看 models.py —— 了解数据库有哪些表、每张表存什么
# 2. 再看 session.py —— 知道怎么连数据库
# 3. 然后看 repositories/ —— 知道怎么查数据
# 4. 最后看 seed.py —— 了解初始化逻辑
