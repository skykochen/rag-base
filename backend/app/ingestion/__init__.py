# ingestion/ 包 —— 文档入库流水线（核心数据处理流程）
#
# 文档从上传到可检索，需要经过一条"流水线"：
#
# 上传文件 → parser.py(解析) → splitter.py(切分) → embedder.py(向量化) → 写入数据库
#
# 【为什么叫"pipeline"（流水线）？】
# 就像工厂的生产线一样，每个工位做一道工序：
# 1. parser：把 PDF/DOCX/MD 等原始文件"读懂"，提取出纯文本
# 2. splitter：把长文本切成小段（chunk），每段 600 字左右
# 3. embedder：把每段文本转成向量（一串数字）
# 4. pipeline：编排上面的步骤，并管理进度和状态
#
# 【Celery 异步执行】
# 文档入库是耗时操作（大文件可能要几分钟），不能同步等。
# 所以上传接口提交任务后立即返回，由 Celery Worker 在后台执行。
# 前端轮询文档状态来获取进度。
#
# 【两个入口】
# - tasks.py：Celery 任务定义（给 worker 用的）
# - pipeline.py：实际的业务逻辑（含首次入库和增量重建）
