# retrieval/ 包 —— 检索层（RAG 的核心检索逻辑）
#
# 用户提问后，系统要找到知识库中相关的文档片段。
# 这个包提供了三种检索方式，层层递进：
#
# 1. vector_retriever.py —— 向量检索（语义理解）
#    把用户问题变成向量，在知识库中找语义相似的文档片段。
#    优点：能理解"意思相近但用词不同"的查询。
#    缺点：对专有名词、编号等精确匹配场景反而不好。
#
# 2. keyword_retriever.py —— 关键词检索（精确匹配）
#    用 PostgreSQL 的中文分词（zhparser）做全文检索。
#    优点：专有名词、编号、制度名等精确匹配场景效果好。
#    缺点：不能理解语义，用词不同就搜不到。
#
# 3. hybrid_retriever.py —— 混合检索（1+2 融合）
#    两路同时召回，用 RRF 算法融合排名。
#    取长补短，既保语义又保精确。
