# api/ 包 —— HTTP 接口层
#
# 这个包处理所有「从网络来的请求」和「返回给客户端的响应」。
# 它是项目的"前台"——用户的所有操作都通过这里的接口触发。
#
# 【为什么要有 API 层？】
# 系统设计有个原则叫「关注点分离」：
# - API 层关心：URL 路径对不对、参数格式对不对、返回什么格式
# - Service 层关心：业务逻辑怎么做
# - Repository 层关心：数据怎么存
# 这样每一层只专注一件事，修改一层的代码不会影响其他层。
#
# routes/     — 路由定义，每个 URL 对应一个函数
# schemas/    — 请求和响应的数据格式定义
# deps.py     — 共享依赖（如获取当前用户、数据库连接）
# error_handlers.py — 统一错误处理
